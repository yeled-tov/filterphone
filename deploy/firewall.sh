#!/usr/bin/env bash
# =====================================================================
# FilterPhone — חומת האש (IPv4). כותב את /etc/iptables/rules.v4 במלואו
# ומחיל אותו בבת אחת (iptables-restore). נטען גם באתחול (netfilter-persistent).
#
# מהאינטרנט: SSH, WireGuard, HTTP/HTTPS (Caddy). כל השאר רק מתוך ה-VPN.
# מתוך ה-VPN: כל ה-DNS מופנה בכוח ל-AdGuard, ‏HTTP/HTTPS לפרוקסי הסינון,
# ‏QUIC ו-DNS מוצפן חיצוני (853) נחסמים כדי שלא יעקפו את הסינון.
# =====================================================================
set -euo pipefail

RULES=/etc/iptables/rules.v4
WG_NET=${FP_VPN_NETWORK:-10.8.0.0/24}
WG_IP=${FP_VPN_SERVER_IP:-10.8.0.1}
PUBLIC_IP=${FP_PUBLIC_IP:-151.145.88.42}
PUB_IF=$(ip -o -4 route show default | awk '{print $5; exit}')
[ -n "$PUB_IF" ] || { echo "לא נמצא ממשק ברירת מחדל"; exit 1; }

# כללי Oracle Cloud (גישה לשירותי המטא-דאטה והאחסון) — חובה לשמר כמו שהם
ORACLE_DECL=$(grep -E '^:InstanceServices ' "$RULES" 2>/dev/null || true)
ORACLE_RULES=$(grep -E '^-A InstanceServices ' "$RULES" 2>/dev/null || true)

tmp=$(mktemp)
cat > "$tmp" <<EOF
# FilterPhone firewall — generated by deploy/firewall.sh, do not edit by hand
*filter
:INPUT ACCEPT [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
${ORACLE_DECL:+$ORACLE_DECL}
-A INPUT -i lo -j ACCEPT
-A INPUT -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A INPUT -p icmp -j ACCEPT
-A INPUT -p tcp -m tcp --dport 22 -m conntrack --ctstate NEW -j ACCEPT
-A INPUT -p udp -m udp --dport 51820 -j ACCEPT
-A INPUT -p tcp -m multiport --dports 80,443 -j ACCEPT
-A INPUT -i wg0 -p udp -m udp --dport 53 -j ACCEPT
-A INPUT -i wg0 -p tcp -m multiport --dports 53,8080,3002 -j ACCEPT
-A INPUT -j REJECT --reject-with icmp-host-prohibited
-A FORWARD -p tcp -m tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu
-A FORWARD -i wg0 -p udp -m udp --dport 443 -j REJECT --reject-with icmp-port-unreachable
-A FORWARD -i wg0 -p tcp -m tcp --dport 853 -j REJECT --reject-with tcp-reset
-A FORWARD -i wg0 -p udp -m udp --dport 853 -j REJECT --reject-with icmp-port-unreachable
-A FORWARD -i wg0 -o $PUB_IF -s $WG_NET -j ACCEPT
-A FORWARD -i $PUB_IF -o wg0 -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A FORWARD -j REJECT --reject-with icmp-host-prohibited
${ORACLE_DECL:+-A OUTPUT -d 169.254.0.0/16 -j InstanceServices}
${ORACLE_RULES}
COMMIT
*nat
:PREROUTING ACCEPT [0:0]
:INPUT ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A PREROUTING -i wg0 -d $WG_IP -j RETURN
-A PREROUTING -i wg0 -p udp -m udp --dport 53 -j DNAT --to-destination $WG_IP:53
-A PREROUTING -i wg0 -p tcp -m tcp --dport 53 -j DNAT --to-destination $WG_IP:53
-A PREROUTING -i wg0 -d $PUBLIC_IP -p tcp -m multiport --dports 80,443 -j DNAT --to-destination $WG_IP
-A PREROUTING -i wg0 -p tcp -m tcp --dport 80 -j REDIRECT --to-ports 8080
-A PREROUTING -i wg0 -p tcp -m tcp --dport 443 -j REDIRECT --to-ports 8080
-A POSTROUTING -s $WG_NET -o $PUB_IF -j MASQUERADE
COMMIT
EOF

sed -i '/^$/d' "$tmp"
# בדיקת תחביר לפני החלה — אם יש טעות, שום דבר לא משתנה
iptables-restore --test < "$tmp"
install -m 640 "$tmp" "$RULES"
rm -f "$tmp"
iptables-restore < "$RULES"
sysctl -qw net.ipv4.ip_forward=1
echo "  חומת האש הוחלה (ממשק ציבורי: $PUB_IF)"
